// Rows carry one or more identifiers in a single string, so pull the tokens out rather
// than matching the whole cell. Longest-first alternation — plain MacBook would swallow
// MacBookPro.
const ID_TOKEN = /(?:MacBookPro|MacBookAir|MacBook|Mac)\d+,\d+/g;

export function identifiersOf(model: Model): string[] {
  return model.modelId.match(ID_TOKEN) ?? [];
}

/** Mac14,2 < Mac14,5 < Mac14,10 — localeCompare alone gets the minor wrong. */
export function compareIdentifiers(a: string, b: string): number {
  const parse = (s: string): [string, number, number] => {
    const m = /^(\D+)(\d+),(\d+)$/.exec(s);
    return m ? [m[1], Number(m[2]), Number(m[3])] : [s, 0, 0];
  };
  const [af, amaj, amin] = parse(a);
  const [bf, bmaj, bmin] = parse(b);
  return af.localeCompare(bf) || amaj - bmaj || amin - bmin;
}

export const ALL_IDENTIFIERS: string[] = [
  ...new Set(MODELS.flatMap(identifiersOf)),
].sort(compareIdentifiers);

